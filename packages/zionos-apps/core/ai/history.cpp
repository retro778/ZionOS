#include "history.h"

#include <QDir>
#include <QFile>
#include <QJsonArray>
#include <QJsonDocument>
#include <QJsonObject>
#include <QRegularExpression>
#include <QSaveFile>
#include <QStandardPaths>
#include <QUuid>

namespace zion::ai {

HistoryStore::HistoryStore(const QString &directory) : m_dir(directory) {}

QString HistoryStore::defaultDirectory()
{
    return QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation)
           + QStringLiteral("/zionos-assistant/conversations");
}

QString HistoryStore::newId()
{
    return QUuid::createUuid().toString(QUuid::WithoutBraces);
}

QString HistoryStore::titleFor(const QString &firstUserMessage)
{
    QString t = firstUserMessage.simplified();
    if (t.size() > 60)
        t = t.left(57) + QStringLiteral("…");
    return t;
}

QString HistoryStore::pathFor(const QString &id) const
{
    // Ids are UUIDs generated by newId(); anything else is rejected so a
    // crafted id can never address a file outside the history directory.
    static const QRegularExpression re(QStringLiteral("^[0-9a-fA-F-]{36}$"));
    if (!re.match(id).hasMatch())
        return {};
    return m_dir + QLatin1Char('/') + id + QStringLiteral(".json");
}

bool HistoryStore::save(const Conversation &c) const
{
    const QString path = pathFor(c.id);
    if (path.isEmpty())
        return false;
    QDir dir(m_dir);
    if (!dir.exists()) {
        if (!QDir().mkpath(m_dir))
            return false;
        QFile::setPermissions(m_dir, QFile::ReadOwner | QFile::WriteOwner | QFile::ExeOwner);
    }
    QJsonArray msgs;
    for (const ChatMessage &m : c.messages) {
        msgs.append(QJsonObject{
            {QStringLiteral("role"), m.role == Role::User ? QStringLiteral("user") : QStringLiteral("assistant")},
            {QStringLiteral("text"), m.text},
        });
    }
    const QJsonObject root{
        {QStringLiteral("format"), 1},
        {QStringLiteral("id"), c.id},
        {QStringLiteral("title"), c.title},
        {QStringLiteral("provider"), c.providerId},
        {QStringLiteral("model"), c.model},
        {QStringLiteral("created"), c.created.toUTC().toString(Qt::ISODate)},
        {QStringLiteral("updated"), c.updated.toUTC().toString(Qt::ISODate)},
        {QStringLiteral("messages"), msgs},
    };
    QSaveFile f(path);
    if (!f.open(QIODevice::WriteOnly))
        return false;
    f.setPermissions(QFile::ReadOwner | QFile::WriteOwner);
    f.write(QJsonDocument(root).toJson(QJsonDocument::Indented));
    return f.commit();
}

bool HistoryStore::load(const QString &id, Conversation *out) const
{
    const QString path = pathFor(id);
    if (path.isEmpty())
        return false;
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly))
        return false;
    QJsonParseError pe;
    const QJsonDocument doc = QJsonDocument::fromJson(f.readAll(), &pe);
    if (pe.error != QJsonParseError::NoError || !doc.isObject())
        return false;
    const QJsonObject o = doc.object();
    Conversation c;
    c.id = id;
    c.title = o.value(QLatin1String("title")).toString();
    c.providerId = o.value(QLatin1String("provider")).toString();
    c.model = o.value(QLatin1String("model")).toString();
    c.created = QDateTime::fromString(o.value(QLatin1String("created")).toString(), Qt::ISODate);
    c.updated = QDateTime::fromString(o.value(QLatin1String("updated")).toString(), Qt::ISODate);
    const QJsonArray msgs = o.value(QLatin1String("messages")).toArray();
    for (const QJsonValue &v : msgs) {
        const QJsonObject m = v.toObject();
        ChatMessage cm;
        cm.role = m.value(QLatin1String("role")).toString() == QLatin1String("assistant")
                      ? Role::Assistant : Role::User;
        cm.text = m.value(QLatin1String("text")).toString();
        c.messages.append(cm);
    }
    *out = c;
    return true;
}

QList<Conversation> HistoryStore::list() const
{
    QList<Conversation> out;
    const QStringList files = QDir(m_dir).entryList({QStringLiteral("*.json")}, QDir::Files);
    for (const QString &f : files) {
        Conversation c;
        if (load(f.chopped(5), &c))
            out.append(c);
    }
    std::sort(out.begin(), out.end(),
              [](const Conversation &a, const Conversation &b) { return a.updated > b.updated; });
    return out;
}

bool HistoryStore::remove(const QString &id) const
{
    const QString path = pathFor(id);
    return !path.isEmpty() && QFile::remove(path);
}

int HistoryStore::removeAll() const
{
    int n = 0;
    QDir dir(m_dir);
    const QStringList files = dir.entryList({QStringLiteral("*.json")}, QDir::Files);
    for (const QString &f : files)
        if (dir.remove(f))
            ++n;
    return n;
}

} // namespace zion::ai
